// Release signing credentials live in the git-ignored keystore.properties at the project root.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.example.tracker"
    compileSdk {
        version = release(36)
    }

    defaultConfig {
        applicationId = "com.example.tracker"
        minSdk = 24
        targetSdk = 36
        // CI passes -PversionCode=<n> and -PversionName=<major.minor.patch> so every pipeline build is a new version.
        // Bump the "1.2" fallback to start a new major/minor line; CI derives the patch from git tags.
        versionCode = providers.gradleProperty("versionCode").orNull?.toInt() ?: 3
        versionName = providers.gradleProperty("versionName").orNull ?: "1.2"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProperties.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
        isCoreLibraryDesugaringEnabled = true
    }
    kotlinOptions {
        jvmTarget = "11"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    testOptions {
        unitTests.isIncludeAndroidResources = true
    }
    lint {
        // CI fails on lint errors; warnings stay visible in the report without failing.
        abortOnError = true
        // Dependency updates are chosen on purpose, not whenever a newer version appears.
        disable += setOf("GradleDependency", "NewerVersionAvailable", "AndroidGradlePluginVersion")
    }
    sourceSets {
        // Exported Room schemas for migration tests. Robolectric only reads the merged debug
        // assets, so they ship in debug builds (never release).
        getByName("debug").assets.srcDir("$projectDir/schemas")
    }
}

room {
    schemaDirectory("$projectDir/schemas")
}

// Kotlin static analysis. Findings already in the code are recorded in the baseline, so CI fails
// only on new ones; regenerate it with ./gradlew detektBaseline after fixing old findings.
detekt {
    buildUponDefaultConfig = true
    config.setFrom(rootProject.file("config/detekt/detekt.yml"))
    baseline = rootProject.file("config/detekt/baseline.xml")
    source.setFrom("src/main/java", "src/test/java", "src/androidTest/java")
}

// Lets CI read the version without parsing this file.
tasks.register("printVersionName") {
    val versionName = android.defaultConfig.versionName
    doLast { println(versionName) }
}

